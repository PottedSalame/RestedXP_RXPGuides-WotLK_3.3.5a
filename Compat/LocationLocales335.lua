local active = translations[GetLocale()]
function addon.LocalizeLegacyLocationName(name)
    if type(name) ~= "string" or not active then return name end
    local exact = active[name]
    if exact then return exact end
    if not name:find(",", 1, true) then return name end
    local parts = {}
    for part in name:gmatch("[^,]+") do
        part = part:gsub("^%s+", ""):gsub("%s+$", "")
        parts[#parts + 1] = active[part] or part
    end
    return table.concat(parts, ", ")
end
