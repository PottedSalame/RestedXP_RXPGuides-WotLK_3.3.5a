"""Website owns its files; optional addon integration uses an explicit checkout."""
import hashlib
import os
from pathlib import Path

WEBSITE=Path(__file__).resolve().parents[1]
PROJECT=WEBSITE.parent
value=os.environ.get('RXP_ADDON_ROOT')
ADDON=Path(value).resolve() if value else (PROJECT if (PROJECT/'RXPGuides.toc').is_file() else None)

def require_addon():
    if ADDON is None or not (ADDON/'RXPGuides.toc').is_file():
        raise ValueError('Set RXP_ADDON_ROOT to a separate RXPGuides addon checkout for this integration check or regeneration.')
    return ADDON

def source_matches(name,expected):
    if name.startswith('website/'):
        path=PROJECT/name
        if hashlib.sha256(path.read_bytes()).hexdigest()==expected:return True
        # Preserve the original producer evidence rather than relabeling data
        # as generated by the relocated tooling. These copies are not executed.
        baseline=WEBSITE/'tools/baseline'/path.name
        return baseline.is_file() and hashlib.sha256(baseline.read_bytes()).hexdigest()==expected
    return hashlib.sha256((require_addon()/name).read_bytes()).hexdigest()==expected
